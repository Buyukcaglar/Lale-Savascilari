#!/usr/bin/env python3
"""
gendgroup.py - generate src/gen/dgroup_init.c: the initial 64 KB DGROUP image.

The port keeps the original data segment as one byte array, `dg[]` (see
src/engine/dgroup.h), so every global sits at its original offset: adjacent
out-of-bounds accesses behave as in the original, and the differential tests
can copy/compare DGROUP between the emulated original and the C port.

Initial bytes = IST.EXE image from 16E0:0000 up to DGROUP's end (60028 bytes);
BSS and the rest are zero (Borland c0 clears 962C-EA7C).  Far pointers stored
in DGROUP (MZ relocations inside it) keep their unrelocated values: the port
never dereferences them (native pointers live outside dg[]); the list is
emitted as dg_farptr_offsets[] for the tests to mask.

usage: gendgroup.py [build/ist_flat.bin] [build/ist_map.json] [src/gen/dgroup_init.c]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DGROUP = 0x16E0
SIZE = 60028                    # segtable maxoff of DGROUP


def main(argv):
    flat = argv[1] if len(argv) > 1 else os.path.join(ROOT, 'build', 'ist_flat.bin')
    mp = argv[2] if len(argv) > 2 else os.path.join(ROOT, 'build', 'ist_map.json')
    out = argv[3] if len(argv) > 3 else os.path.join(ROOT, 'src', 'gen', 'dgroup_init.c')
    img = open(flat, 'rb').read()
    info = json.load(open(mp))
    data = img[DGROUP * 16: DGROUP * 16 + SIZE]
    far = sorted(int(r[5:], 16) for r in info['relocations'] if r.startswith('16E0:'))
    last = len(data.rstrip(b'\0'))
    data = data[:last]
    lines = ['/* GENERATED by tools/gendgroup.py from IST.EXE - do not edit. */',
             '#include "engine/dgroup.h"', '',
             f'/* initial DGROUP 16E0:0000-{last:04X}; the rest (BSS, stack) is zero */',
             f'const uint8_t dg_init[{last}] = {{']
    for i in range(0, last, 24):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines += ['};', f'const uint16_t dg_init_size = {last};', '',
              '/* offsets of the segment word of far pointers initialised in DGROUP */',
              f'const uint16_t dg_farptr_offsets[{len(far)}] = {{']
    for i in range(0, len(far), 12):
        lines.append('    ' + ','.join(f'0x{o:04X}' for o in far[i:i + 12]) + ',')
    lines += ['};', f'const uint16_t dg_farptr_count = {len(far)};', '']
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print(f'gendgroup: {last} initial bytes, {len(far)} far-pointer words -> {out}')


if __name__ == '__main__':
    main(sys.argv)
